async function run(page) {
  const R = [];
  const rec = (name, pass, detail) => R.push({ name, pass: !!pass, detail: detail === undefined ? null : detail });
  const consoleErrs = [];
  page.on("console", (m) => { if (m.type() === "error") consoleErrs.push(m.text()); });
  page.on("pageerror", (e) => consoleErrs.push("pageerror: " + e.message));
  const getLog = async () => (await (await page.request.get(BASE + "/__log")).json());
  await page.setViewportSize({ width: 360, height: 640 });
  await page.goto(BASE + "/demo.html");
  await page.waitForSelector("[data-vc-widget]", { state: "attached" });
  const bubble = page.locator(".bubble");
  rec("bubble visible", await bubble.isVisible());
  rec("panel hidden initially", !(await page.locator(".panel").isVisible()));
  await bubble.click();
  rec("panel opens", await page.locator(".panel").isVisible());
  rec("dialog role + aria-expanded", (await page.locator(".panel").getAttribute("role")) === "dialog" && (await bubble.getAttribute("aria-expanded")) === "true");
  rec("greeting shown", (await page.locator(".log .m").first().innerText()).startsWith("Hi, I am an AI"));
  const foot = await page.locator(".foot").innerText();
  rec("footer 14416/112 shown", foot.includes("14416") && foot.includes("112"), foot);
  const send = async (t) => { await page.locator("textarea").fill(t); await page.locator("textarea").press("Enter"); };
  await send("which course after 12th");
  await page.waitForSelector(".m.bot:has(.claims)");
  const bot = page.locator(".m.bot").last();
  const botText = await bot.innerText();
  rec("normal turn: message + 2 claims (1 flagged) + 1 source link", botText.includes("Computer Science") && (await bot.locator(".claims li").count()) === 2 && (await bot.locator(".src a").count()) === 1 && botText.includes("(unverified)"), botText);
  rec("source link https + noopener", (await bot.locator(".src a").getAttribute("href")) === "https://www.aicte-india.org/" && (await bot.locator(".src a").getAttribute("rel")).includes("noopener"));
  const log1 = await getLog();
  rec("key mode request: X-VC-Key sent, body exactly {text}, no cookie", log1[0].path === "/v1/public/chat/turns" && log1[0].key === "vck_demo_key" && log1[0].body === JSON.stringify({ text: "which course after 12th" }) && log1[0].cookie === null, log1[0]);
  await page.locator("textarea").fill("slow one");
  await page.locator("textarea").press("Enter");
  const typingShown = await page.locator(".typing").isVisible();
  const sendDis = await page.locator(".send").isDisabled();
  rec("typing indicator shown and send disabled while waiting", typingShown && sendDis, { typingShown, sendDis });
  await page.waitForSelector(".typing", { state: "hidden" });
  await send("xss please");
  await page.waitForFunction(() => document.querySelector("[data-vc-widget]").shadowRoot.querySelectorAll(".m.bot").length >= 4);
  const xss = await page.evaluate(() => { const sr = document.querySelector("[data-vc-widget]").shadowRoot; return { injected: sr.querySelectorAll(".m img, .m script, .m b, .m i").length, noFlag: window.__xss === undefined, text: Array.from(sr.querySelectorAll(".m.bot")).pop().textContent }; });
  rec("XSS inert: no img/script/b/i elements, no flag set", xss.injected === 0 && xss.noFlag, xss);
  await send("nosource please");
  await page.waitForSelector(".m.note");
  const hrefs = await page.locator(".m.note").last().locator("a").evaluateAll((as) => as.map((a) => a.href));
  rec("no_sourced_answer: https link kept, javascript: link dropped", hrefs.length === 1 && hrefs[0] === "https://example.org/page", hrefs);
  await send("crisis now");
  await page.waitForSelector(".m.crisis");
  const cr = await page.locator(".m.crisis").last().innerText();
  rec("escalated renders crisis block with helpline", cr.includes("14416") && cr.includes("112"), cr);
  await send("boom");
  await page.waitForSelector(".m.err");
  const e500 = await page.locator(".m.err").last().innerText();
  rec("500 shows error with helpline", e500.includes("500") && e500.includes("14416"), e500);
  await send("ratelimit");
  await page.waitForFunction(() => /Please wait/.test(document.querySelector("[data-vc-widget]").shadowRoot.querySelector(".status").textContent));
  const dis429 = await page.locator(".send").isDisabled();
  const restored = await page.locator("textarea").inputValue();
  rec("429: countdown shown, send disabled, message restored", dis429 && restored === "ratelimit", { dis429, restored, status: await page.locator(".status").innerText() });
  await page.waitForFunction(() => !document.querySelector("[data-vc-widget]").shadowRoot.querySelector(".send").disabled, null, { timeout: 8000 });
  rec("429: send re-enabled after Retry-After (3 s)", true);
  await page.locator("textarea").fill("");
  const geo = await page.evaluate(() => { const sr = document.querySelector("[data-vc-widget]").shadowRoot; const p = sr.querySelector(".panel").getBoundingClientRect(); const b = sr.querySelector(".bubble").getBoundingClientRect(); return { l: p.left, r: p.right, t: p.top, b: p.bottom, vw: innerWidth, vh: innerHeight, scrollW: document.documentElement.scrollWidth, bubbleR: b.right }; });
  rec("360px: panel inside viewport, no horizontal scroll", geo.l >= 0 && geo.r <= geo.vw && geo.t >= 0 && geo.b <= geo.vh && geo.scrollW <= geo.vw, geo);
  await page.screenshot({ path: OUT + "/360px.png" });
  await page.keyboard.press("Escape");
  rec("Esc closes panel and focus returns to bubble", !(await page.locator(".panel").isVisible()) && (await page.evaluate(() => document.querySelector("[data-vc-widget]").shadowRoot.activeElement.className)) === "bubble");
  const st = await page.evaluate(() => ({ ls: localStorage.length, ss: sessionStorage.length, ck: document.cookie }));
  rec("no localStorage, sessionStorage or cookies", st.ls === 0 && st.ss === 0 && st.ck === "", st);
  await page.setViewportSize({ width: 1280, height: 800 });
  await bubble.click();
  const dg = await page.evaluate(() => { const p = document.querySelector("[data-vc-widget]").shadowRoot.querySelector(".panel").getBoundingClientRect(); return { w: p.width, h: p.height }; });
  rec("desktop: panel 380 px wide", Math.round(dg.w) === 380, dg);
  await page.screenshot({ path: OUT + "/desktop.png" });
  await send("revoke");
  await page.waitForFunction(() => /Chat unavailable/.test(document.querySelector("[data-vc-widget]").shadowRoot.querySelector(".log").textContent));
  const un = await page.locator(".m.err").last().innerText();
  rec("401 shows 'Chat unavailable' and disables input", un.startsWith("Chat unavailable") && (await page.locator("textarea").isDisabled()) && (await page.locator(".send").isDisabled()), un);
  await page.goto(BASE + "/demo.html?mode=proxy");
  await page.waitForSelector("[data-vc-widget]", { state: "attached" });
  await page.locator(".bubble").click();
  await send("hello proxy");
  await page.waitForSelector(".m.bot:has(.claims)");
  const log2 = await getLog();
  const last = log2[log2.length - 1];
  rec("proxy mode: posted to /api/vc with no X-VC-Key", last.path === "/api/vc" && last.key === null && last.body === JSON.stringify({ text: "hello proxy" }), last);
  await page.locator("textarea").fill("line1");
  await page.locator("textarea").press("Shift+Enter");
  rec("Shift+Enter does not send", (await getLog()).length === log2.length);
  rec("console errors (JS): none beyond deliberately injected 4xx/5xx resource loads", consoleErrs.filter((e) => !/Failed to load resource/.test(e)).length === 0, consoleErrs);
  return R;
}
