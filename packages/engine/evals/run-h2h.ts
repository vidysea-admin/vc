#!/usr/bin/env node
/**
 * P1 U4: `pnpm --filter @vc/engine eval:h2h [--golden=<jsonl>] [--fixture=<json>] [--seed=<s>] [--out=<dir>] [--real]`
 * (spec A14 plumbing). Mock mode: VC answers come from the frozen KB fixture, expert answers and
 * judge ratings are SYNTHETIC, so the tally is plumbing only. It writes the blind pairs (no origin),
 * the secret key, one judge sheet per judge and the report. `--real` refuses without VC_G_REAL=1 and
 * runs under the A24 budget guard.
 */
import { fileURLToPath } from "node:url";
import { readFileSync } from "node:fs";
import { z } from "zod";
import {
  DEFAULT_GOLDEN_SET,
  DEFAULT_KB_FIXTURE,
  RealNotWiredError,
  assertRealInputAllowed,
  RealReport,
  p1Main,
  runRealPath,
  writeP1File,
  writeP1Report,
  type P1Args,
  type RealBody,
  type RunnerDeps,
  type RunnerOutcome,
} from "./run-eval.js";
import { fixtureSearch, loadGoldenSet, loadKbFixture } from "./dataset.js";
import { NO_SOURCED_ANSWER_TEXT } from "./probes.js";
import { buildBlindPairs, buildJudgeSheets, buildKeyFile, resolveH2hSeed, tallyH2h, type ExpertAnswer, type H2hRating } from "./h2h.js";
import { judgeSheetMarkdown, toH2hMarkdown } from "./report.js";

const MOCK_AUTHORS = ["author-1", "author-2"];
const MOCK_JUDGES = ["judge-1", "judge-2"];

const VcAnswerSchema = z.object({ answer: z.string().min(1) });
const ExpertAnswerSchema = z.object({ questionId: z.string().min(1), text: z.string().min(1), author: z.string().min(1) });
/** `--experts` file: a bare array (counsellor-written answers), or `{source, experts}` so a file can declare it holds recorded (real) text. */
const ExpertsFileSchema = z.union([
  z.array(ExpertAnswerSchema).transform((experts) => ({ source: "synthetic" as const, experts })),
  z.object({ source: z.enum(["synthetic", "recorded"]), experts: z.array(ExpertAnswerSchema) }),
]);
/** Eval-harness prompt (not a product skill). */
const H2H_PROMPT =
  "You are a study-abroad counsellor's assistant. Answer the student's question using ONLY the supplied knowledge-base passages, in at most five sentences. " +
  'Do not quote the passages verbatim. Return JSON only: {"answer": "<text>"}.';

/**
 * U13b / A14 REAL body (VC_REAL_MODEL=ollama:<id>): the VC side of every pair is generated by `provider`
 * from the question's top-3 fixture passages (a question with no recorded passages gets the fixed
 * no-sourced-answer text, with no model call). Expert answers come from `--experts=<json>`; without it
 * they are labelled placeholders and the report says so. Writes the blind pairs, the secret key (random
 * seed unless --seed), and the judge sheets; there are no ratings yet, so the tally is NOT PROVEN until
 * two counsellor judges fill the sheets in.
 */
export function realH2hBody(args: P1Args): RealBody {
  const golden = loadGoldenSet(args.golden ?? DEFAULT_GOLDEN_SET);
  const fixture = loadKbFixture(args.fixture ?? DEFAULT_KB_FIXTURE);
  assertRealInputAllowed("run-h2h", "--fixture", fixture.source, args);
  const expertsFile = args.experts ? ExpertsFileSchema.parse(JSON.parse(readFileSync(args.experts, "utf-8"))) : undefined;
  if (expertsFile) assertRealInputAllowed("run-h2h", "--experts", expertsFile.source, args);
  const provided = expertsFile?.experts;
  const experts: ExpertAnswer[] = golden.map((g, i) => {
    const given = provided?.find((e) => e.questionId === g.id);
    if (provided && !given) throw new Error(`run-h2h --experts: no expert answer for question ${g.id}`);
    return given ?? { questionId: g.id, text: `[PLACEHOLDER: replace with a counsellor-written answer for ${g.id}]`, author: MOCK_AUTHORS[i % MOCK_AUTHORS.length]! };
  });
  return async (_run, provider) => {
    if (!provider) throw new RealNotWiredError("run-h2h");
    const vcAnswers: Record<string, string> = {};
    for (const g of golden) {
      const top = [...(fixtureSearch(fixture, g.question) ?? [])].sort((a, b) => b.score - a.score).slice(0, 3);
      if (top.length === 0) {
        vcAnswers[g.id] = NO_SOURCED_ANSWER_TEXT;
        continue;
      }
      const out = await provider.generate({
        skillName: "eval-h2h-vc-answer",
        skillPrompt: H2H_PROMPT,
        outputSchema: VcAnswerSchema,
        input: { question: g.question, passages: top.map((h) => ({ node_id: h.turnId, text: h.turn.text })) },
      });
      vcAnswers[g.id] = out.answer;
    }
    const resolved = resolveH2hSeed({ real: true, ...(args.seed !== undefined ? { seed: args.seed } : {}) });
    const { pairs, key } = buildBlindPairs(
      golden.map((g) => ({ id: g.id, question: g.question })),
      vcAnswers,
      experts,
      resolved.seed,
    );
    const sheets = buildJudgeSheets(pairs, experts, MOCK_JUDGES, resolved.seed);
    writeP1File(args.outDir, "h2h-pairs.json", `${JSON.stringify(pairs, null, 2)}\n`);
    writeP1File(args.outDir, "h2h-key.json", `${JSON.stringify(buildKeyFile(resolved, key), null, 2)}\n`);
    for (const sheet of sheets) {
      writeP1File(args.outDir, `h2h-judge-sheet-${sheet.judge}.json`, `${JSON.stringify(sheet, null, 2)}\n`);
      writeP1File(args.outDir, `h2h-judge-sheet-${sheet.judge}.md`, judgeSheetMarkdown(sheet));
    }
    const tally = tallyH2h(key, [], {
      judges: MOCK_JUDGES,
      a1Met: false, // a real run reads the A1/A3 REAL reports; not read here, so not claimed
      a3Met: false,
      authorsByQuestion: Object.fromEntries(experts.map((e) => [e.questionId, e.author])),
    });
    const expertsSource = provided ? "counsellor-written (--experts)" : "PLACEHOLDER (no --experts given)";
    const markdown = [
      `> REAL run: model \`${provider.model}\` wrote ${golden.length} VC answer(s). Expert answers: ${expertsSource}. Blind pairs, secret key and judge sheets are written; no ratings yet, so A14 is NOT PROVEN until two counsellor judges rate them.`,
      "",
      toH2hMarkdown(tally, { mode: "real" }),
    ].join("\n");
    return new RealReport({ mode: "real", model: provider.model, expertsSource, seedSource: resolved.source, tally }, markdown);
  };
}

export async function runH2h(args: P1Args, deps: RunnerDeps = {}): Promise<RunnerOutcome> {
  if (args.real) return runRealPath("run-h2h", "h2h", args, deps, () => realH2hBody(args));
  const golden = loadGoldenSet(args.golden ?? DEFAULT_GOLDEN_SET);
  const fixture = loadKbFixture(args.fixture ?? DEFAULT_KB_FIXTURE);
  const questions = golden.map((g) => ({ id: g.id, question: g.question }));
  const vcAnswers: Record<string, string> = {};
  for (const g of golden) {
    const top = [...(fixtureSearch(fixture, g.question) ?? [])].sort((a, b) => b.score - a.score)[0];
    vcAnswers[g.id] = top ? `[mock answer] ${top.turn.text}` : "[mock answer] no sourced answer yet";
  }
  const experts: ExpertAnswer[] = golden.map((g, i) => ({ questionId: g.id, text: `[mock answer] reference for ${g.id}`, author: MOCK_AUTHORS[i % MOCK_AUTHORS.length]! }));
  const resolved = resolveH2hSeed({ real: false, ...(args.seed !== undefined ? { seed: args.seed } : {}) });
  const { pairs, key } = buildBlindPairs(questions, vcAnswers, experts, resolved.seed);
  const sheets = buildJudgeSheets(pairs, experts, MOCK_JUDGES, resolved.seed);

  const files: string[] = [];
  files.push(writeP1File(args.outDir, "h2h-pairs.json", `${JSON.stringify(pairs, null, 2)}\n`));
  files.push(writeP1File(args.outDir, "h2h-key.json", `${JSON.stringify(buildKeyFile(resolved, key), null, 2)}\n`));
  for (const sheet of sheets) {
    files.push(writeP1File(args.outDir, `h2h-judge-sheet-${sheet.judge}.json`, `${JSON.stringify(sheet, null, 2)}\n`));
    files.push(writeP1File(args.outDir, `h2h-judge-sheet-${sheet.judge}.md`, judgeSheetMarkdown(sheet)));
  }

  // SYNTHETIC ratings: every judge prefers VC on 13 of every 20 questions. Plumbing only.
  const ratings: H2hRating[] = [];
  for (const judge of MOCK_JUDGES) {
    for (const [i, k] of key.entries()) {
      const prefersVc = i % 20 < 13;
      ratings.push({ judge, questionId: k.questionId, preference: prefersVc ? k.vcSide : k.vcSide === "A" ? "B" : "A", safetyA: false, safetyB: false });
    }
  }
  const tally = tallyH2h(key, ratings, {
    judges: MOCK_JUDGES,
    a1Met: true, // mock assumption; a real run reads the A1/A3 REAL reports
    a3Met: true,
    authorsByQuestion: Object.fromEntries(experts.map((e) => [e.questionId, e.author])),
  });
  const markdown = toH2hMarkdown(tally, { mode: "mock" });
  files.push(...writeP1Report(args.outDir, "h2h", { mode: "mock", note: "synthetic ratings, plumbing only", tally }, markdown));
  return { runner: "run-h2h", mode: "mock", status: "completed", report: tally, markdown, files };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) p1Main(runH2h);
